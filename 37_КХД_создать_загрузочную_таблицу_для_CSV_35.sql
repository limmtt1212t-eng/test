/*
Запускать в Oracle перед импортом CSV из запроса №35.

Зачем таблица создаётся заранее
--------------------------------
CSV не хранит типы данных. DBeaver пытается угадать их по
нескольким строкам. Из-за значения false он может ошибочно
предложить BOOLEAN, который не подходит для колонки в текущей
версии Oracle.

Поэтому загрузочная таблица принимает значения как текст.
Точные типы будут преобразовываться уже в запросе соединения.

Важно
------
- Не запусать CREATE TABLE повторно, если таблица уже создана.
- Если получена ORA-00955, значит SPHERE_OBJECTS_35 уже существует.
- Таблица создаётся в текущей схеме Oracle.
*/

create table SPHERE_OBJECTS_35 (
    "ID договора" varchar2(200),
    "Номер договора" varchar2(500),
    "Статус договора" varchar2(500),
    "Дата начала договора" varchar2(100),
    "Дата окончания договора" varchar2(100),

    "СС по договору" varchar2(200),
    "Валюта СС по договору" varchar2(100),
    "Мин. СС среди объектов договора" varchar2(200),
    "Макс. СС среди объектов договора" varchar2(200),

    "ID объекта" varchar2(200),
    "Название объекта" varchar2(4000),
    "Описание объекта" clob,
    "Площадь объекта" varchar2(200),
    "Тип объекта" varchar2(500),
    "СС объекта из связи с задачей" varchar2(200),
    "Валюта СС объекта из связи" varchar2(100),
    "Мин. СС объекта из условий" varchar2(200),
    "Макс. СС объекта из условий" varchar2(200),
    "Валюты СС объекта из условий" varchar2(500),

    "Полный адрес" varchar2(4000),
    "Адрес как ввели" clob,
    "ФИАС объекта" varchar2(500),
    "ID адреса 2ГИС" varchar2(500),

    "ID страхователя" varchar2(200),
    "ИНН страхователя" varchar2(100),
    "ID страхователя в CDI" varchar2(200),
    "ID CRM-карточки" varchar2(200),
    "ID заявки" varchar2(200),
    "ID задачи" varchar2(200),
    "ID связи задачи и объекта" varchar2(200),
    "ID характеристик объекта" varchar2(200),
    "ID адреса" varchar2(200),

    "Условие: тип задачи" varchar2(500),
    "Условие: статус задачи" varchar2(500),
    "Условие: тип документа" varchar2(500),
    "Условие: установлен отказ" varchar2(50)
);

